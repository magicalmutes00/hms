CREATE TABLE IF NOT EXISTS idempotency_keys (
  id UUID PRIMARY KEY,
  user_id VARCHAR(255) NOT NULL,
  key_hash VARCHAR(64) NOT NULL,
  request_path VARCHAR(255) NOT NULL,
  response_body TEXT,
  status_code INT,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  CONSTRAINT uq_idemp_user_hash_path UNIQUE (user_id, key_hash, request_path)
);

CREATE INDEX IF NOT EXISTS idx_idemp_expires_at ON idempotency_keys (expires_at);
CREATE INDEX IF NOT EXISTS idx_idemp_user ON idempotency_keys (user_id);
